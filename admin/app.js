/* The website editor. Vanilla ES modules, no framework, no build step — same as the
   rest of this repo, and for the same reason: a chapter officer's website should
   still be editable in five years without anyone reinstalling a toolchain.

   HOW IT WORKS (the Bound at the Seams model): the officer sees the real page, full width,
   rendered by js/blocks.js — the SAME module the Worker runs at save time, so what they see
   before saving is generated by the identical code that generates what ships. Words are typed
   straight into the page; a photo, a button or an event opens a short panel for just that one
   thing. Nothing is sent until the one Save button, which commits through /api/save.

   ⛔ NOTHING HERE IS A SECURITY CONTROL. Every check in this file is a courtesy to
   the person using it. The real validation is functions/api/save.js, which does
   not trust a single byte of what this sends. If the two ever disagree, the
   endpoint is right. */
import { renderPage, pathKey, eventItems } from '../js/blocks.js';
import { validateContent, contentFingerprint } from '../js/validate-content.js';
import { FIELDS, HERO_FIELDS, ADVANCED_KEYS, BLOCK_LABELS, BLOCK_DEFAULTS, linesToText, textToLines, isSimpleLines } from './fields.js';

const $ = (sel, root = document) => root.querySelector(sel);
const el = (tag, props = {}, kids = []) => {
  const node = Object.assign(document.createElement(tag), props);
  for (const kid of [].concat(kids)) node.append(kid);
  return node;
};

const state = {
  content: null, site: null, page: 0,
  pristine: '',        // JSON of what was last loaded or saved: Discard goes back to it
  base: null,          // fingerprint of the stored content, for /api/save's stale-editor check
  links: true,         // false when private meeting links couldn't be loaded (see /api/content)
  dirty: false, saving: false, note: '', error: '', errorPath: null,
  drawer: null,        // { kind: 'item' | 'block', path } | { kind: 'hero' } | { kind: 'layout' }
};

/* What one entry of each list is called, for "Event details", "+ Add another photo"… */
const NOUN = { events: 'event', cards: 'card', gallery: 'photo', officers: 'officer', buttons: 'button',
               list: 'point', iconRows: 'row' };
const ITEM_DEFAULT = { events: () => ({}), cards: () => ({}), gallery: () => ({}), officers: () => ({}),
                       buttons: () => ({ variant: 'primary' }), list: () => '', iconRows: () => ({ lines: [] }) };
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const an = (noun) => (/^[aeiou]/.test(noun) ? 'an ' : 'a ') + noun;

/* ---------- loading ---------- */

const snapshot = () => JSON.stringify({ content: state.content, site: state.site });

async function loadSite() {
  /* Straight from the branch (/api/content), so an officer who saved a minute ago and reopens
     the editor doesn't load the pre-save copy the not-yet-rebuilt site still serves. Falls back
     to the deployed files if that endpoint is unavailable. */
  let content, site, base = null, links = true;
  try {
    const r = await fetch('../api/content', { cache: 'no-store' }).then((x) => x.json());
    if (!r.ok) throw new Error(r.error);
    ({ content, site } = r);
    base = typeof r.base === 'string' ? r.base : null;
    links = r.links !== false;
  } catch {
    const bust = '?t=' + Date.now();
    [content, site] = await Promise.all([
      fetch('../content/pages.json' + bust).then((r) => r.json()),
      fetch('../content/site.json' + bust).then((r) => r.json()),
    ]);
    links = false;
  }
  state.content = content;
  state.site = site;
  state.base = base || await contentFingerprint(content, site);
  state.links = links;
  state.pristine = snapshot();
  state.dirty = false;
}

/* ---------- paths ----------
   Everything on a page is addressed by a dotted path from the page object, the same strings
   js/blocks.js writes into the preview: "hero.title", "sections.1.blocks.0.items.2.title". */

const curPage = () => state.content.pages[state.page];
function getAt(root, path) {
  if (!path) return root;
  return path.split('.').reduce((o, k) => (o === null || o === undefined ? undefined : o[k]), root);
}
function setAt(root, path, value) {
  const i = path.lastIndexOf('.');
  const parent = getAt(root, path.slice(0, i));
  if (parent && typeof parent === 'object') parent[path.slice(i + 1)] = value;
}
const parentOf = (path) => path.slice(0, path.lastIndexOf('.'));
const lastOf = (path) => path.slice(path.lastIndexOf('.') + 1);

/* ---------- event registration ids ----------
   Minted ONCE, when an event first takes registration, from its date and name, and never
   recomputed — sign-ups are stored against it, so renaming the event must not orphan them.
   The same event listed on two pages (same date and name) shares one id. */
const slugify = (s) => String(s || '').toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
function ensureEventIds() {
  const all = eventItems(state.content);
  const key = (e) => [e.month, e.day, e.title].map((x) => String(x || '').trim().toLowerCase()).join('|');
  for (const e of all) {
    const wants = e.register === true || (typeof e.meetingLink === 'string' && e.meetingLink.trim());
    if (!wants || e.id || !String(e.title || '').trim()) continue;
    const twin = all.find((o) => o !== e && o.id && key(o) === key(e));
    if (twin) { e.id = twin.id; continue; }
    const base = slugify([e.month, e.day, e.title].filter(Boolean).join(' ')).slice(0, 56).replace(/-+$/, '') || 'event';
    let id = base, n = 2;
    while (all.some((o) => o !== e && o.id === id)) id = base + '-' + n++;
    e.id = id;
  }
}

/* ---------- after every change ---------- */

let previewTimer = null;
function changed({ preview = true, drawer = false, now = false } = {}) {
  ensureEventIds();
  state.dirty = snapshot() !== state.pristine;   // typing a word and deleting it again is "no change"
  state.note = '';
  state.error = '';
  updateStatus();
  if (drawer) renderDrawer();
  if (preview) {
    clearTimeout(previewTimer);
    // Typing in a panel redraws the page a beat later, not on every key.
    if (now) renderPreview(); else previewTimer = setTimeout(renderPreview, 250);
  }
}

function updateStatus() {
  const check = validateContent(state.content);
  const status = $('#status');
  state.errorPath = null;
  if (!check.ok) {
    status.className = 'status status--bad';
    status.textContent = describe(check.path) + ' ' + check.error;
    state.errorPath = check.path;
  } else if (state.error) {
    status.className = 'status status--bad';
    status.textContent = state.error;
  } else {
    status.className = 'status' + (state.dirty ? ' status--dirty' : state.note ? ' status--good' : '');
    status.textContent = state.dirty ? 'You have changes that aren’t saved yet.' : state.note || 'Everything is saved.';
  }
  $('#save').disabled = !check.ok || !state.dirty || state.saving;
  $('#discard').disabled = !state.dirty || state.saving;
}

/* "pages[2].sections[0].blocks[1].items[3].meetingLink" -> "On the Events page, “Fall Tour”:"
   An officer can't act on an array path; they can act on "which page, which event". */
function describe(path) {
  const dotted = String(path || '').replace(/\[(\d+)\]/g, '.$1');
  const m = /^pages\.(\d+)/.exec(dotted);
  const page = m && state.content.pages[Number(m[1])];
  if (!page) return '';
  const item = /^(.*\.items\.\d+)/.exec(dotted);
  const thing = item && getAt(state.content, item[1]);
  const name = thing && (thing.title || thing.name || thing.label);
  return 'On the ' + pageName(state.content.pages.indexOf(page)) + ' page' + (name ? ', “' + name + '”' : '') + ':';
}

function pageName(i) {
  const page = state.content.pages[i];
  const nav = (state.site.nav || []).find((l) => l && l.href === page.navHref);
  return (nav && nav.label) || (page.slug === 'index' ? 'Home' : (page.hero && page.hero.title) || page.slug);
}

