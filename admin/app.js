async function signIn(event) {
  event.preventDefault();
  const error = $('#signin-error');
  error.textContent = '';
  const res = await fetch('../api/login', {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ username: $('#username').value, password: $('#password').value }),
  }).catch(() => null);
  const body = res ? await res.json().catch(() => ({})) : {};
  if (!res || !res.ok || !body.ok) { error.textContent = body.error || 'That didn’t work. Please try again.'; return; }
  await start();
}

/* ---------- event sign-ups (D1, NOT content) ----------
   Who registered. This lives in the database and never touches the website's files (see
   functions/api/rsvp.js). Registration itself is switched on per event, on the page, in the
   event's details — this screen is for reading, exporting and tidying the lists. */

function setMode(m) {
  const content = m === 'content';
  $('#content-view').hidden = !content;
  $('#savebar').hidden = !content;
  $('#events-view').hidden = content;
  if (!content) { state.drawer = null; renderDrawer(); }
  for (const [id, on] of [['#mode-content', content], ['#mode-events', !content]]) {
    $(id).classList.toggle('is-on', on);
    $(id).setAttribute('aria-pressed', on ? 'true' : 'false');
  }
  if (!content) loadEvents();
}

const when = (iso) => {
  const d = new Date(iso);
  return isNaN(d) ? '' : d.toLocaleString(undefined, { dateStyle: 'medium', timeStyle: 'short' });
};

async function loadEvents() {
  const view = $('#events-view');
  view.textContent = '';
  view.append(el('h1', { className: 'ev-h', textContent: 'Event sign-ups' }));
  view.append(el('p', { className: 'hint', textContent: 'People who registered on the website. To let people register for an event, go to “Change the website”, open the Events page, press “Event details” on the event and tick “Let people register on the website”, then save.' }));
  const list = el('div', { className: 'ev-list', textContent: 'Loading…' });
  view.append(list);
  let events = [];
  try {
    const r = await fetch('../api/events').then((x) => x.json());
    if (!r.ok) throw new Error(r.error);
    events = r.events;
  } catch (e) { list.textContent = 'The sign-ups couldn’t be loaded. ' + (e.message || 'Please refresh the page.'); return; }
  list.textContent = '';
  if (!events.length) { list.append(el('p', { className: 'empty', textContent: 'No events are taking registrations yet.' })); return; }
  events.forEach((ev) => list.append(eventCard(ev)));
}

function eventCard(ev) {
  const seats = ev.seats || 0;
  const closed = !!ev.closed;
  const box = el('div', { className: 'ev-rsvps', hidden: true });
  const view = el('button', { className: 'btn btn--primary', type: 'button', textContent: `See who registered (${seats})` });
  view.addEventListener('click', () => {
    box.hidden = !box.hidden;
    view.textContent = box.hidden ? `See who registered (${seats})` : 'Hide the list';
    if (!box.hidden) loadRsvps(ev, box);
  });
  const toggle = el('button', { className: 'btn btn--quiet', type: 'button',
    textContent: closed ? 'Start taking sign-ups again' : 'Stop taking sign-ups' });
  toggle.addEventListener('click', async () => {
    toggle.disabled = true;
    try {
      await fetch('../api/events', { method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ id: ev.id, title: ev.title, capacity: ev.capacity, closed: closed ? 0 : 1 }) });
    } catch {}
    loadEvents();
  });
  const actions = [view, toggle];
  if (seats === 0) {   // the server refuses to delete an event that still has sign-ups (they'd cascade)
    const del = el('button', { className: 'btn btn--danger', type: 'button', textContent: 'Delete this event’s sign-up list' });
    del.addEventListener('click', async () => {
      if (!confirm(`Delete the sign-up list for “${ev.title}”? It’s empty.`)) return;
      del.disabled = true;
      const res = await fetch('../api/events/delete', { method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ id: ev.id }) }).then((x) => x.json()).catch(() => ({ ok: false, error: 'Network error.' }));
      if (!res.ok) { del.disabled = false; alert(res.error || 'That couldn’t be deleted.'); return; }
      loadEvents();
    });
    actions.push(del);
  }
  return el('section', { className: 'ev-card' }, [
    el('div', { className: 'ev-card-head' }, [
      el('h2', { className: 'ev-name', textContent: ev.title }),
      el('span', { className: 'ev-badge ' + (closed ? 'ev-badge--closed' : 'ev-badge--open'),
        textContent: closed ? 'Not taking sign-ups' : 'Taking sign-ups' }),
      el('span', { className: 'ev-seats', textContent: `${seats} registered` + (ev.capacity ? ` of ${ev.capacity} places` : '') }),
    ]),
    el('div', { className: 'ev-actions' }, actions),
    box,
  ]);
}

async function loadRsvps(ev, box) {
  box.textContent = 'Loading…';
  let data;
  try { data = await fetch('../api/rsvps?event_id=' + encodeURIComponent(ev.id)).then((x) => x.json()); }
  catch { box.textContent = 'The list couldn’t be loaded. Please try again.'; return; }
  if (!data.ok) { box.textContent = data.error || 'The list couldn’t be loaded.'; return; }
  const rsvps = data.rsvps;
  box.textContent = '';
  const head = el('div', { className: 'ev-rsvps-head' }, [
    el('p', { className: 'ev-count', textContent: `${rsvps.length} ${rsvps.length === 1 ? 'person' : 'people'} registered` }),
  ]);
  if (rsvps.length) {
    head.append(el('a', { className: 'btn btn--quiet', href: '../api/rsvps?format=csv&event_id=' + encodeURIComponent(ev.id),
      textContent: 'Download the list (spreadsheet)' }));
  }
  box.append(head);
  if (!rsvps.length) { box.append(el('p', { className: 'empty', textContent: 'Nobody has registered yet.' })); return; }
  const table = el('table', { className: 'ev-table' });
  table.append(el('thead', {}, el('tr', {}, ['Name', 'Phone', 'Email', 'Registered', ''].map((h) => el('th', { scope: 'col', textContent: h })))));
  const tb = el('tbody');
  for (const r of rsvps) {
    const tel = String(r.phone || '').replace(/[^+\d]/g, '');
    const del = el('button', { className: 'btn btn--danger btn--sm', type: 'button', textContent: 'Remove' });
    del.addEventListener('click', async () => {
      if (!confirm(`Remove ${r.name} from the list?`)) return;
      del.disabled = true;
      const res = await fetch('../api/rsvps/delete', { method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ id: r.id }) }).then((x) => x.json()).catch(() => ({ ok: false }));
      if (res.ok) loadRsvps(ev, box); else { del.disabled = false; alert(res.error || 'That couldn’t be removed.'); }
    });
    // Every value goes in as text (el sets textContent): names and emails come from strangers.
    tb.append(el('tr', {}, [
      el('td', { textContent: r.name }),
      el('td', {}, r.phone ? el('a', { href: 'tel:' + tel, textContent: r.phone }) : ''),
      el('td', {}, el('a', { href: 'mailto:' + r.email, textContent: r.email })),
      el('td', { textContent: when(r.created_at) }),
      el('td', {}, del),
    ]));
  }
  table.append(tb);
  box.append(el('div', { className: 'ev-table-wrap' }, table));
}

