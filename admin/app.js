/* The site manager. Vanilla ES modules, no framework, no build step — same as the
   rest of this repo, and for the same reason: a chapter officer's website should
   still be editable in five years without anyone reinstalling a toolchain.

   ⛔ NOTHING HERE IS A SECURITY CONTROL. Every check in this file is a courtesy to
   the person using it. The real validation is functions/api/save.js, which does
   not trust a single byte of what this sends. If the two ever disagree, the
   endpoint is right.

   The preview renders with js/blocks.js — the SAME module the Worker uses at save
   time. That is what the dual-runtime byte-match test buys: what an officer sees
   before saving is generated by the identical code that generates what ships. */
import { renderPage } from '../js/blocks.js';
import { validateContent } from '../js/validate-content.js';
import { FIELDS, BLOCK_LABELS, BLOCK_DEFAULTS, linesToText, textToLines, isSimpleLines } from './fields.js';

const $ = (sel, root = document) => root.querySelector(sel);
const el = (tag, props = {}, kids = []) => {
  const node = Object.assign(document.createElement(tag), props);
  for (const kid of [].concat(kids)) node.append(kid);
  return node;
};

const state = { content: null, site: null, sel: null, dirty: false, saving: false };

/* ---------- loading ---------- */

async function loadSite() {
  /* Cache-busted, because the officer may have saved minutes ago and a stale copy
     would silently discard whatever they just published. */
  const bust = '?t=' + Date.now();
  const [content, site] = await Promise.all([
    fetch('../content/pages.json' + bust).then((r) => r.json()),
    fetch('../content/site.json' + bust).then((r) => r.json()),
  ]);
  state.content = content;
  state.site = site;
  state.sel = { page: 0, path: null };
}

/* ---------- selection paths ----------
   A block is addressed by the chain of indexes that reaches it, so the same code
   handles a top-level block and one nested inside a split's left column. */

function containerAt(page, path) {
  // path: { section, chain: [{ index, key? }] } — key is 'blocks' | 'left' | 'right'
  let list = page.sections[path.section].blocks;
  for (const step of path.chain) list = list[step.index][step.key];
  return list;
}
function blockAt(page, path) {
  const list = path.chain.length
    ? containerAt(page, { section: path.section, chain: path.chain.slice(0, -1) })
    : page.sections[path.section].blocks;
  const last = path.chain.length ? path.chain[path.chain.length - 1] : null;
  return last ? list[last.index] : null;
}
const samePath = (a, b) => JSON.stringify(a) === JSON.stringify(b);

/* ---------- outline ---------- */

function renderOutline() {
  const wrap = $('#outline');
  wrap.textContent = '';

  const pageList = el('div', { className: 'pages' });
  state.content.pages.forEach((page, i) => {
    const row = el('button', {
      className: 'page-tab' + (i === state.sel.page ? ' is-on' : ''),
      type: 'button',
      textContent: page.slug,
      onclick: () => { state.sel = { page: i, path: null }; render(); },
    });
    pageList.append(row);
  });
  pageList.append(el('button', {
    className: 'page-tab page-tab--add', type: 'button', textContent: '+ Page',
    onclick: addPage,
  }));
  wrap.append(pageList);

  const page = state.content.pages[state.sel.page];
  if (!page) return;

  wrap.append(el('div', { className: 'page-meta' }, [
    field('Address', page.slug, (v) => { page.slug = v; touch(); }, { hint: 'lowercase, no spaces — becomes ' + page.slug + '.html' }),
    field('Browser tab title', page.title || '', (v) => { page.title = v; touch(); }),
    field('Hero title', page.hero ? page.hero.title : '', (v) => {
      if (!page.hero) page.hero = { variant: 'page', title: v }; else page.hero.title = v;
      touch();
    }),
    field('Hero eyebrow', page.hero ? page.hero.kicker || '' : '', (v) => {
      if (page.hero) page.hero.kicker = v; touch();
    }),
  ]));

  (page.sections || []).forEach((section, si) => {
    const box = el('div', { className: 'section-box' });
    box.append(el('div', { className: 'section-head' }, [
      el('span', { className: 'section-name', textContent: 'Section ' + (si + 1) }),
      toggle('Tinted', section.tint, (v) => { section.tint = v; touch(); }),
      toggle('Dark', section.dark, (v) => { section.dark = v; touch(); }),
      toggle('Narrow', section.narrow, (v) => { section.narrow = v; touch(); }),
      toggle('Tight', section.tight, (v) => { section.tight = v; touch(); }),
      el('button', { className: 'x', type: 'button', textContent: '✕', title: 'Delete this section',
        onclick: () => removeSection(si) }),
    ]));
    box.append(blockList(page, { section: si, chain: [] }, section.blocks || []));
    wrap.append(box);
  });

  wrap.append(el('button', {
    className: 'add-section', type: 'button', textContent: '+ Add section',
    onclick: () => { page.sections = page.sections || []; page.sections.push({ blocks: [] }); touch(); },
  }));
}

function blockList(page, basePath, blocks) {
  const list = el('div', { className: 'block-list' });
  blocks.forEach((block, bi) => {
    const path = { section: basePath.section, chain: basePath.chain.concat([{ index: bi, key: 'blocks' }]) };
    const label = BLOCK_LABELS[block.type] ? BLOCK_LABELS[block.type][0] : block.type;
    const row = el('div', { className: 'block-row' + (samePath(path, state.sel.path) ? ' is-on' : '') });
    row.append(el('button', {
      className: 'block-name', type: 'button',
      textContent: label + summarise(block),
      onclick: () => { state.sel = { page: state.sel.page, path }; render(); },
    }));
    row.append(el('button', { className: 'mv', type: 'button', textContent: '↑', title: 'Move up',
      disabled: bi === 0, onclick: () => move(blocks, bi, -1) }));
    row.append(el('button', { className: 'mv', type: 'button', textContent: '↓', title: 'Move down',
      disabled: bi === blocks.length - 1, onclick: () => move(blocks, bi, 1) }));
    row.append(el('button', { className: 'x', type: 'button', textContent: '✕', title: 'Delete this block',
      onclick: () => { blocks.splice(bi, 1); state.sel.path = null; touch(); } }));
    list.append(row);

    /* A container's children are nested in the outline, which is the only place
       the structure is visible — the preview shows the result, not the shape. */
    if (block.type === 'group') {
      list.append(el('div', { className: 'nest' },
        blockList(page, { section: basePath.section, chain: path.chain }, block.blocks || [])));
      list.append(nestAdd(block, 'blocks', 'block inside this group'));
    } else if (block.type === 'split') {
      for (const side of ['left', 'right']) {
        list.append(el('div', { className: 'nest' }, [
          el('div', { className: 'nest-label', textContent: side + ' column' }),
          blockList(page, { section: basePath.section, chain: path.chain.slice(0, -1).concat([{ index: bi, key: side }]) },
                    block[side] || []),
          nestAdd(block, side, side + ' column'),
        ]));
      }
    }
  });
  list.append(addBlockButton(blocks));
  return list;
}

function nestAdd(block, key, what) {
  block[key] = block[key] || [];
  return addBlockButton(block[key], 'Add a ' + what);
}

function addBlockButton(target, label) {
  const wrap = el('div', { className: 'add-block' });
  const select = el('select', { className: 'add-select' });
  select.append(el('option', { value: '', textContent: label || '+ Add block' }));
  for (const [type, [name, hint]] of Object.entries(BLOCK_LABELS)) {
    select.append(el('option', { value: type, textContent: name + ' — ' + hint }));
  }
  select.onchange = () => {
    if (!select.value) return;
    target.push(BLOCK_DEFAULTS[select.value]());
    select.value = '';
    touch();
  };
  wrap.append(select);
  return wrap;
}

/* A few words from the block itself, so the outline is scannable without
   clicking every row to find out which paragraph is which. */
function summarise(block) {
  const first = block.title || block.text || block.heading ||
                (Array.isArray(block.items) && block.items.length
                  ? (typeof block.items[0] === 'string' ? block.items[0] : block.items[0].title || block.items[0].label || block.items[0].name || '')
                  : '');
  const text = String(first || '').replace(/\s+/g, ' ').trim();
  return text ? ' · ' + (text.length > 34 ? text.slice(0, 34) + '…' : text) : '';
}

function move(list, index, delta) {
  const target = index + delta;
  if (target < 0 || target >= list.length) return;
  const [item] = list.splice(index, 1);
  list.splice(target, 0, item);
  state.sel.path = null;
  touch();
}

function removeSection(index) {
  state.content.pages[state.sel.page].sections.splice(index, 1);
  state.sel.path = null;
  touch();
}

function addPage() {
  const slug = prompt('Address for the new page (lowercase, no spaces):', 'new-page');
  if (!slug) return;
  state.content.pages.push({
    slug: slug.trim().toLowerCase(),
    navHref: slug.trim().toLowerCase() + '.html',
    title: 'New page',
    hero: { variant: 'page', kicker: '', title: 'New page' },
    sections: [{ blocks: [] }],
  });
  state.sel = { page: state.content.pages.length - 1, path: null };
  touch();
}

/* ---------- the block editor ---------- */

function renderEditor() {
  const wrap = $('#editor');
  wrap.textContent = '';
  if (!state.sel.path) {
    wrap.append(el('p', { className: 'empty', textContent: 'Pick a block on the left to edit it.' }));
    return;
  }
  const page = state.content.pages[state.sel.page];
  const block = blockAt(page, state.sel.path);
  if (!block) { state.sel.path = null; return; }

  const [name, hint] = BLOCK_LABELS[block.type] || [block.type, ''];
  wrap.append(el('h2', { textContent: name }));
  wrap.append(el('p', { className: 'hint', textContent: hint }));

  for (const spec of FIELDS[block.type] || []) {
    wrap.append(renderField(block, spec));
  }
}

function renderField(obj, spec) {
  if (spec.kind === 'items') return renderItems(obj, spec);
  const value = obj[spec.key];

  if (spec.kind === 'check') return toggle(spec.label, value, (v) => { obj[spec.key] = v; touch(); }, true);

  if (spec.kind === 'select') {
    const sel = el('select', { className: 'input' });
    for (const opt of spec.options) {
      sel.append(el('option', { value: opt, textContent: opt === '' ? '(default)' : opt, selected: (value || '') === opt }));
    }
    sel.onchange = () => { if (sel.value) obj[spec.key] = sel.value; else delete obj[spec.key]; touch(); };
    return labelled(spec, sel);
  }

  if (spec.kind === 'long') {
    const ta = el('textarea', { className: 'input', rows: 4, value: value || '' });
    ta.oninput = () => { obj[spec.key] = ta.value; touch(false); };
    return labelled(spec, ta);
  }

  if (spec.kind === 'number') {
    const input = el('input', { className: 'input', type: 'number', value: value ?? '', min: spec.min, max: spec.max });
    input.oninput = () => { obj[spec.key] = input.value === '' ? undefined : Number(input.value); touch(false); };
    return labelled(spec, input);
  }

  const input = el('input', { className: 'input', type: 'text', value: value || '' });
  input.oninput = () => { obj[spec.key] = input.value; touch(false); };
  const row = labelled(spec, input);
  if (spec.kind === 'image') row.append(uploadButton(input, obj, spec.key));
  return row;
}

function renderItems(block, spec) {
  const box = el('div', { className: 'items' });
  box.append(el('div', { className: 'items-head', textContent: spec.label }));
  const list = block[spec.key] = block[spec.key] || [];

  list.forEach((item, i) => {
    const card = el('div', { className: 'item' });
    card.append(el('div', { className: 'item-head' }, [
      el('span', { textContent: '#' + (i + 1) }),
      el('button', { className: 'mv', type: 'button', textContent: '↑', disabled: i === 0,
        onclick: () => move(list, i, -1) }),
      el('button', { className: 'mv', type: 'button', textContent: '↓', disabled: i === list.length - 1,
        onclick: () => move(list, i, 1) }),
      el('button', { className: 'x', type: 'button', textContent: '✕',
        onclick: () => { list.splice(i, 1); touch(); } }),
    ]));

    if (spec.simple) {
      // A plain list of strings (the bulleted list), not objects.
      const input = el('input', { className: 'input', type: 'text', value: item || '' });
      input.oninput = () => { list[i] = input.value; touch(false); };
      card.append(input);
    } else {
      for (const sub of spec.fields) {
        if (sub.lines) {
          /* iconRows: hide the spans structure behind one text box, but only when
             the row is simple enough to survive the round trip. */
          if (!isSimpleLines(item.lines)) {
            card.append(el('p', { className: 'hint',
              textContent: 'This row contains a link or bold text and is edited in the content file.' }));
            continue;
          }
          const input = el('input', { className: 'input', type: 'text', value: linesToText(item.lines) });
          input.oninput = () => { item.lines = textToLines(input.value); touch(false); };
          card.append(labelled(sub, input));
          continue;
        }
        card.append(renderField(item, sub));
      }
    }
    box.append(card);
  });

  box.append(el('button', {
    className: 'add-item', type: 'button', textContent: '+ Add',
    onclick: () => { list.push(spec.simple ? '' : {}); touch(); },
  }));
  return box;
}

function labelled(spec, control) {
  const row = el('label', { className: 'field' }, [
    el('span', { className: 'field-label', textContent: spec.label + (spec.required ? ' *' : '') }),
    control,
  ]);
  if (spec.hint) row.append(el('span', { className: 'field-hint', textContent: spec.hint }));
  return row;
}

function field(label, value, onInput, opts = {}) {
  const input = el('input', { className: 'input', type: 'text', value: value || '' });
  input.oninput = () => onInput(input.value);
  return labelled({ label, hint: opts.hint }, input);
}

function toggle(label, value, onChange, block) {
  const input = el('input', { type: 'checkbox', checked: !!value });
  input.onchange = () => onChange(input.checked);
  return el('label', { className: block ? 'field field--check' : 'chip' }, [input, el('span', { textContent: label })]);
}

function uploadButton(input, obj, key) {
  const picker = el('input', { type: 'file', accept: 'image/*', className: 'hidden-file' });
  const button = el('button', { className: 'upload', type: 'button', textContent: 'Upload…',
    onclick: () => picker.click() });
  picker.onchange = async () => {
    const file = picker.files && picker.files[0];
    if (!file) return;
    button.textContent = 'Uploading…';
    button.disabled = true;
    try {
      const form = new FormData();
      form.append('file', file);
      form.append('dest', 'site');
      const res = await fetch('../api/upload', { method: 'POST', body: form });
      const body = await res.json();
      if (!res.ok || !body.ok) throw new Error(body.error || 'Upload failed.');
      input.value = body.path;
      obj[key] = body.path;
      touch();
    } catch (e) {
      alert('That photo could not be uploaded. ' + (e.message || ''));
    } finally {
      button.textContent = 'Upload…';
      button.disabled = false;
    }
  };
  return el('span', { className: 'upload-wrap' }, [button, picker]);
}

/* ---------- preview ---------- */

function renderPreview() {
  const page = state.content.pages[state.sel.page];
  if (!page) return;
  let html;
  try {
    html = renderPage(page, state.site);
  } catch (e) {
    html = '<p style="font:15px sans-serif;padding:24px">This page can’t be previewed yet: ' + e.message + '</p>';
  }
  /* srcdoc has no document URL, so every relative path in the page would break.
     A <base> pointing at the site root fixes them all in one line. */
  $('#preview').srcdoc = html.replace('<head>', '<head><base href="' + new URL('..', location.href).href + '">');
}

/* ---------- saving ---------- */

function touch(full = true) {
  state.dirty = true;
  $('#save').disabled = false;
  updateStatus();
  if (full) render(); else renderPreview();
}

function updateStatus() {
  const check = validateContent(state.content);
  const status = $('#status');
  if (!check.ok) {
    status.className = 'status status--bad';
    status.textContent = check.path + ' ' + check.error;
    $('#save').disabled = true;
    return;
  }
  status.className = 'status' + (state.dirty ? ' status--dirty' : '');
  status.textContent = state.dirty ? 'You have unsaved changes.' : 'Everything is saved.';
  $('#save').disabled = !state.dirty || state.saving;
}

async function saveSite() {
  if (state.saving) return;
  state.saving = true;
  $('#save').disabled = true;
  $('#save').textContent = 'Saving…';
  try {
    const res = await fetch('../api/save', {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ content: state.content, site: state.site }),
    });
    const body = await res.json();
    if (res.status === 401) { showSignIn(); return; }
    if (!res.ok || !body.ok) throw new Error(body.error || 'Save failed.');
    state.dirty = false;
    $('#status').className = 'status status--good';
    $('#status').textContent = body.note || 'Saved.';
  } catch (e) {
    $('#status').className = 'status status--bad';
    $('#status').textContent = e.message;
  } finally {
    state.saving = false;
    $('#save').textContent = 'Save changes';
    updateStatus();
  }
}

/* ---------- sign in ---------- */

function showSignIn() { $('#signin').hidden = false; $('#app').hidden = true; }
function showApp() { $('#signin').hidden = true; $('#app').hidden = false; }

async function signIn(event) {
  event.preventDefault();
  const error = $('#signin-error');
  error.textContent = '';
  const res = await fetch('../api/login', {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ username: $('#username').value, password: $('#password').value }),
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok || !body.ok) { error.textContent = body.error || 'That didn’t work.'; return; }
  await start();
}

