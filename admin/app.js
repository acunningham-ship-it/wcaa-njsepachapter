function renderPreview() {
  clearTimeout(previewTimer);
  const page = curPage();
  if (!page) return;
  let html;
  try {
    html = renderPage(page, state.site, { edit: true });
  } catch (e) {
    html = '<p style="font:18px sans-serif;padding:24px">This page can’t be shown yet: ' + e.message + '</p>';
  }
  /* srcdoc has no document URL, so every relative path in the page would break.
     A <base> pointing at the site root fixes them all in one line. */
  const frame = $('#preview');
  // Re-rendering replaces the document; keep the officer's place on the page.
  const y = frame.contentWindow ? frame.contentWindow.scrollY : 0;
  frame.onload = () => { frame.contentWindow.scrollTo(0, y); wirePreview(frame.contentDocument); };
  frame.srcdoc = html.replace('<head>', '<head><base href="' + new URL('..', location.href).href + '">');
}

function wirePreview(doc) {
  if (!doc || !doc.body) return;
  doc.head.append(Object.assign(doc.createElement('style'), { textContent: EDITOR_CSS }));

  /* plaintext-only where the browser has it: pasted or typed formatting can't sneak in. The
     model only ever stores the text (textContent) either way. */
  let mode = 'true';
  try { const t = doc.createElement('div'); t.contentEditable = 'plaintext-only'; if (t.contentEditable === 'plaintext-only') mode = 'plaintext-only'; } catch {}
  for (const n of doc.querySelectorAll('[data-f]')) {
    n.contentEditable = mode;
    n.spellcheck = true;
    n.setAttribute('role', 'textbox');
    n.setAttribute('aria-label', 'Change this text');
  }

  /* Every event, card and officer gets a visible "… details" button. Clicking its words types
     into them, so without the button there'd be nowhere obvious to click for the date, the
     registration switch or the meeting link — and nothing here may depend on hovering. */
  for (const n of doc.querySelectorAll('[data-item]')) {
    if (!n.querySelector('[data-f]')) continue;
    const type = blockTypeOfItem(n.getAttribute('data-item'));
    const b = doc.createElement('button');
    b.type = 'button';
    b.className = 'wcaa-edit-details';
    b.setAttribute('data-open', n.getAttribute('data-item'));
    b.textContent = '✎ ' + cap(NOUN[type] || 'item') + ' details';
    (n.querySelector('.wcaa-ev__body') || n).append(b);
  }
  const hero = doc.querySelector('[data-hero]');
  if (hero) {
    const b = doc.createElement('button');
    b.type = 'button';
    b.className = 'wcaa-edit-details wcaa-edit-details--hero';
    b.setAttribute('data-open', 'hero');
    b.textContent = '✎ Banner photo and buttons';
    hero.append(b);
  }

  doc.addEventListener('input', (ev) => {
    const n = ev.target && ev.target.closest ? ev.target.closest('[data-f]') : null;
    if (!n) return;
    const path = n.getAttribute('data-f');
    setAt(curPage(), path, n.textContent.replace(/\s*\n\s*/g, ' '));
    changed({ preview: false, drawer: drawerShows(path) });
  });
  doc.addEventListener('keydown', (ev) => {
    if (!ev.target.closest || !ev.target.closest('[data-f]')) return;
    if (ev.key === 'Enter' || ev.key === 'Escape') { ev.preventDefault(); ev.target.blur(); }
  });
  // Pasting from an email or a Word file brings formatting along; keep only the words.
  doc.addEventListener('paste', (ev) => {
    if (!ev.target.closest || !ev.target.closest('[data-f]')) return;
    ev.preventDefault();
    const text = (ev.clipboardData ? ev.clipboardData.getData('text/plain') : '').replace(/\s+/g, ' ');
    doc.execCommand('insertText', false, text);
  });
  doc.addEventListener('drop', (ev) => ev.preventDefault(), true);
  doc.addEventListener('submit', (ev) => ev.preventDefault(), true);

  // Capture phase: links and buttons on the page never navigate while editing.
  doc.addEventListener('click', (ev) => {
    const t = ev.target && ev.target.closest ? ev.target : null;
    ev.preventDefault();
    if (!t) return;
    const add = t.closest('[data-add]');
    if (add) { ev.stopPropagation(); return addItem(add.getAttribute('data-add')); }
    const open = t.closest('[data-open]');
    if (open) {
      ev.stopPropagation();
      const target = open.getAttribute('data-open');
      return openDrawer(target === 'hero' ? { kind: 'hero' } : { kind: 'item', path: target });
    }
    if (t.closest('[data-f]')) return;   // typing in place: the caret is already there
    ev.stopPropagation();
    const item = t.closest('[data-item]');
    if (item) return openDrawer({ kind: 'item', path: item.getAttribute('data-item') });
    if (t.closest('[data-hero]')) return openDrawer({ kind: 'hero' });
    const block = t.closest('[data-edit]');
    if (block) {
      try { openDrawer({ kind: 'block', path: pathKey(JSON.parse(block.getAttribute('data-edit'))) }); } catch {}
    }
  }, true);
}

function blockTypeOfItem(itemPath) {
  const block = getAt(curPage(), parentOf(parentOf(itemPath)));
  return block && block.type;
}

/* Is the open panel showing the field the officer just typed into on the page? */
function drawerShows(fieldPath) {
  const d = state.drawer;
  if (!d) return false;
  if (d.kind === 'hero') return fieldPath.startsWith('hero.');
  if (d.kind === 'item' || d.kind === 'block') return fieldPath.startsWith(d.path + '.');
  return false;
}

/* ---------- adding to a list ---------- */

function addItem(listPath) {
  const page = curPage();
  const block = getAt(page, parentOf(listPath));
  if (!block || !NOUN[block.type]) return;
  block.items = Array.isArray(block.items) ? block.items : [];
  block.items.push(ITEM_DEFAULT[block.type]());
  openDrawer({ kind: 'item', path: listPath + '.' + (block.items.length - 1) }, { focus: true });
  changed({ now: true });
}

/* An entry added and then left completely blank isn't saved as an invisible, empty event. */
function isBlank(v) {
  if (v === null || v === undefined) return true;
  if (typeof v === 'string') return !v.trim();
  if (Array.isArray(v)) return v.every(isBlank);
  if (typeof v === 'object') return Object.keys(v).filter((k) => k !== 'variant').every((k) => isBlank(v[k]));
  return v === false;
}

/* ---------- the side panel ---------- */

function openDrawer(target, { focus = false } = {}) {
  const pruned = pruneBlankItem();
  if (pruned && target.kind === 'item' && parentOf(target.path) === pruned.list) {
    const i = Number(lastOf(target.path));
    if (i === pruned.index) return closeDrawer();
    if (i > pruned.index) target = { kind: 'item', path: pruned.list + '.' + (i - 1) };
  }
  state.drawer = target;
  renderDrawer();
  if (focus) { const first = $('#drawer-body input, #drawer-body textarea'); if (first) first.focus(); }
  else $('#drawer-close').focus();
}

function closeDrawer() {
  pruneBlankItem();
  state.drawer = null;
  renderDrawer();
  changed({ now: true });
}

function pruneBlankItem() {
  const d = state.drawer;
  if (!d || d.kind !== 'item') return null;
  const list = getAt(curPage(), parentOf(d.path));
  const i = Number(lastOf(d.path));
  if (!Array.isArray(list) || i >= list.length || !isBlank(list[i])) return null;
  list.splice(i, 1);
  return { list: parentOf(d.path), index: i };
}

function renderDrawer() {
  const d = state.drawer;
  const drawer = $('#drawer');
  document.body.classList.toggle('has-drawer', !!d);
  if (!d) { drawer.hidden = true; return; }
  const body = $('#drawer-body');
  body.textContent = '';
  let title = '';
  if (d.kind === 'item') title = itemPanel(body, d.path);
  else if (d.kind === 'block') title = blockPanel(body, d.path);
  else if (d.kind === 'hero') title = heroPanel(body);
  else if (d.kind === 'layout') title = layoutPanel(body);
  if (title === null) { state.drawer = null; drawer.hidden = true; document.body.classList.remove('has-drawer'); return; }
  $('#drawer-title').textContent = title;
  drawer.hidden = false;
}

function itemPanel(body, path) {
  const page = curPage();
  const listPath = parentOf(path);
  const index = Number(lastOf(path));
  const block = getAt(page, parentOf(listPath));
  const list = getAt(page, listPath);
  if (!block || !Array.isArray(list) || index >= list.length) return null;
  const item = list[index];
  const spec = (FIELDS[block.type] || []).find((f) => f.kind === 'items');
  const noun = NOUN[block.type] || 'item';
  if (!spec) return null;

  if (spec.simple) {
    const input = el('input', { className: 'input', type: 'text', value: item || '' });
    input.oninput = () => { list[index] = input.value; changed(); };
    body.append(labelled({ label: cap(noun) }, input));
  } else {
    const style = el('details', { className: 'more' }, el('summary', { textContent: 'Style' }));
    for (const sub of spec.fields) {
      if (sub.lines) { body.append(linesField(item, sub)); continue; }
      if (ADVANCED_KEYS.includes(sub.key)) { style.append(renderField(item, sub)); continue; }
      body.append(renderField(item, sub));
      if (block.type === 'events' && sub.key === 'meetingLink' && !state.links) {
        body.append(el('p', { className: 'field-hint field-hint--warn',
          textContent: 'Saved meeting links couldn’t be loaded just now, so this box may look empty even if a link is saved. Leave it empty to keep the saved link.' }));
      }
    }
    if (style.children.length > 1) body.append(style);
  }

  const row = el('div', { className: 'drawer-actions' });
  row.append(el('button', { className: 'btn btn--quiet', type: 'button', textContent: 'Move earlier', disabled: index === 0,
    onclick: () => moveItem(list, listPath, index, -1) }));
  row.append(el('button', { className: 'btn btn--quiet', type: 'button', textContent: 'Move later', disabled: index === list.length - 1,
    onclick: () => moveItem(list, listPath, index, 1) }));
  row.append(el('button', { className: 'btn btn--danger', type: 'button', textContent: 'Remove this ' + noun,
    onclick: () => {
      const name = typeof item === 'string' ? item : item.title || item.name || item.label || item.caption || '';
      if (!confirm('Remove ' + (name ? '“' + name + '”' : 'this ' + noun) + ' from the page? You can still press “Discard changes” before saving.')) return;
      list.splice(index, 1);
      state.drawer = null;
      renderDrawer();
      changed({ now: true });
    } }));
  body.append(row);
  body.append(el('button', { className: 'btn btn--add', type: 'button', textContent: '+ Add another ' + noun,
    onclick: () => addItem(listPath) }));
  body.append(moreSettings(block));
  return cap(noun) + ' details';
}

function moveItem(list, listPath, index, delta) {
  const to = index + delta;
  if (to < 0 || to >= list.length) return;
  const [it] = list.splice(index, 1);
  list.splice(to, 0, it);
  state.drawer = { kind: 'item', path: listPath + '.' + to };
  changed({ drawer: true, now: true });
}

/* Layout settings (spacing, columns, alignment) for the list or block, folded away. */
function moreSettings(block) {
  const specs = (FIELDS[block.type] || []).filter((s) => s.kind !== 'items' && ADVANCED_KEYS.includes(s.key));
  if (!specs.length) return el('span');
  const box = el('details', { className: 'more' });
  box.append(el('summary', { textContent: 'Layout settings (spacing, columns)' }));
  for (const s of specs) box.append(renderField(block, s));
  return box;
}

function blockPanel(body, path) {
  const page = curPage();
  const block = getAt(page, path);
  if (!block || !FIELDS[block.type]) return null;
  const [name, hint] = BLOCK_LABELS[block.type] || [block.type, ''];
  if (hint) body.append(el('p', { className: 'hint', textContent: hint }));

  for (const spec of FIELDS[block.type]) {
    if (ADVANCED_KEYS.includes(spec.key)) continue;
    if (spec.kind !== 'items') { body.append(renderField(block, spec)); continue; }
    // A list: the simple ones edit inline here, the rest list their entries to open one at a time.
    if (spec.simple || block.type === 'iconRows') { body.append(renderItems(block, spec)); continue; }
    const noun = NOUN[block.type] || 'item';
    const box = el('div', { className: 'items' });
    box.append(el('div', { className: 'items-head', textContent: spec.label }));
    (block.items || []).forEach((it, i) => {
      box.append(el('button', { className: 'item-row', type: 'button',
        textContent: (it && (it.title || it.name || it.label || it.caption || it.alt)) || cap(noun) + ' ' + (i + 1),
        onclick: () => openDrawer({ kind: 'item', path: path + '.items.' + i }) }));
    });
    box.append(el('button', { className: 'btn btn--add', type: 'button', textContent: '+ Add ' + an(noun),
      onclick: () => addItem(path + '.items') }));
    body.append(box);
  }
  body.append(moreSettings(block));
  body.append(el('div', { className: 'drawer-actions' }, [
    el('button', { className: 'btn btn--danger', type: 'button', textContent: 'Remove this from the page',
      onclick: () => {
        if (!confirm('Remove this ' + name.toLowerCase() + ' from the page? You can still press “Discard changes” before saving.')) return;
        getAt(page, parentOf(path)).splice(Number(lastOf(path)), 1);
        state.drawer = null;
        renderDrawer();
        changed({ now: true });
      } }),
  ]));
  return name;
}

function heroPanel(body) {
  const page = curPage();
  if (!page.hero) page.hero = { variant: 'page', title: pageName(state.page) };
  for (const spec of HERO_FIELDS) body.append(spec.kind === 'items' ? renderItems(page.hero, spec) : renderField(page.hero, spec));
  return 'Page banner';
}

/* ---------- fields ---------- */

function renderField(obj, spec) {
  if (spec.kind === 'items') return renderItems(obj, spec);
  const value = obj[spec.key];

  if (spec.kind === 'check') {
    const input = el('input', { type: 'checkbox', checked: !!value });
    input.onchange = () => { obj[spec.key] = input.checked; changed({ drawer: true, now: true }); };
    const row = el('label', { className: 'field field--check' }, [input, el('span', { textContent: spec.label })]);
    return spec.hint ? el('div', {}, [row, el('p', { className: 'field-hint', textContent: spec.hint })]) : row;
  }

  if (spec.kind === 'select') {
    const sel = el('select', { className: 'input' });
    for (const opt of spec.options) {
      sel.append(el('option', { value: opt, textContent: opt === '' ? '(standard)' : opt, selected: (value || '') === opt }));
    }
    sel.onchange = () => { if (sel.value) obj[spec.key] = sel.value; else delete obj[spec.key]; changed(); };
    return labelled(spec, sel);
  }

  if (spec.kind === 'long') {
    const ta = el('textarea', { className: 'input', rows: 4, value: value || '' });
    ta.oninput = () => { obj[spec.key] = ta.value; changed(); };
    return labelled(spec, ta);
  }

  if (spec.kind === 'number') {
    const input = el('input', { className: 'input', type: 'number', value: value ?? '', min: spec.min, max: spec.max });
    input.oninput = () => { obj[spec.key] = input.value === '' ? undefined : Number(input.value); changed(); };
    return labelled(spec, input);
  }

  const input = el('input', { className: 'input', type: spec.key === 'meetingLink' ? 'url' : 'text', value: value || '' });
  if (spec.key === 'meetingLink') { input.inputMode = 'url'; input.placeholder = 'https://…'; }
  input.oninput = () => { obj[spec.key] = input.value; changed(); };
  const row = labelled(spec, input);
  if (spec.kind === 'image') row.append(uploadButton(input, obj, spec.key));
  return row;
}

/* A list edited in place (bulleted points, icon rows, a banner's buttons). */
function renderItems(block, spec) {
  const box = el('div', { className: 'items' });
  box.append(el('div', { className: 'items-head', textContent: spec.label }));
  const list = block[spec.key] = block[spec.key] || [];

  list.forEach((item, i) => {
    const card = el('div', { className: 'item' });
    card.append(el('div', { className: 'item-head' }, [
      el('span', { textContent: '#' + (i + 1) }),
      el('button', { className: 'mv', type: 'button', textContent: 'Up', disabled: i === 0,
        onclick: () => { move(list, i, -1); } }),
      el('button', { className: 'mv', type: 'button', textContent: 'Down', disabled: i === list.length - 1,
        onclick: () => { move(list, i, 1); } }),
      el('button', { className: 'mv mv--x', type: 'button', textContent: 'Remove',
        onclick: () => { list.splice(i, 1); changed({ drawer: true, now: true }); } }),
    ]));
    if (spec.simple) {
      const input = el('input', { className: 'input', type: 'text', value: item || '' });
      input.oninput = () => { list[i] = input.value; changed(); };
      card.append(input);
    } else {
      for (const sub of spec.fields) card.append(sub.lines ? linesField(item, sub) : renderField(item, sub));
    }
    box.append(card);
  });

  box.append(el('button', {
    className: 'btn btn--add', type: 'button', textContent: '+ Add ' + an((ITEM_NOUN[spec.label] || 'item')),
    onclick: () => { list.push(spec.simple ? '' : {}); changed({ drawer: true, now: true }); },
  }));
  return box;
}

/* iconRows: hide the spans structure behind one text box, but only when the row is simple
   enough to survive the round trip. */
function linesField(item, sub) {
  if (!isSimpleLines(item.lines)) {
    return el('p', { className: 'hint', textContent: 'This row contains a link or bold text and is changed by your web person.' });
  }
  const input = el('input', { className: 'input', type: 'text', value: linesToText(item.lines) });
  input.oninput = () => { item.lines = textToLines(input.value); changed(); };
  return labelled(sub, input);
}

const ITEM_NOUN = { Events: 'event', Cards: 'card', Photos: 'photo', Officers: 'officer',
                    Buttons: 'button', Points: 'point', Rows: 'row' };

function move(list, index, delta) {
  const target = index + delta;
  if (target < 0 || target >= list.length) return;
  const [item] = list.splice(index, 1);
  list.splice(target, 0, item);
  changed({ drawer: true, now: true });
}

function labelled(spec, control) {
  const row = el('label', { className: 'field' }, [
    el('span', { className: 'field-label', textContent: spec.label + (spec.required ? ' (needed)' : '') }),
    control,
  ]);
  if (spec.hint) row.append(el('span', { className: 'field-hint', textContent: spec.hint }));
  return row;
}

function uploadButton(input, obj, key) {
  const picker = el('input', { type: 'file', accept: 'image/*', className: 'hidden-file' });
  const button = el('button', { className: 'btn btn--quiet', type: 'button', textContent: 'Choose a photo…',
    onclick: () => picker.click() });
  picker.onchange = async () => {
    const file = picker.files && picker.files[0];
    if (!file) return;
    button.textContent = 'Uploading…';
    button.disabled = true;
    try {
      const form = new FormData();
      form.append('file', file);
      form.append('dest', 'site');
      const res = await fetch('../api/upload', { method: 'POST', body: form });
      const body = await res.json();
      if (!res.ok || !body.ok) throw new Error(body.error || 'Upload failed.');
      input.value = body.path;
      obj[key] = body.path;
      changed({ now: true });
    } catch (e) {
      alert('That photo couldn’t be uploaded. ' + (e.message || ''));
    } finally {
      button.textContent = 'Choose a photo…';
      button.disabled = false;
    }
  };
  return el('span', { className: 'upload-wrap' }, [button, picker]);
}

